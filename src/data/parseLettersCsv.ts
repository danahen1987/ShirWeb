const HEBREW_START = /[\u05D0-\u05EA]/;

export function parseWordCell(cell: string): ExampleWord {
  const trimmed = cell.trim();
  const index = trimmed.search(HEBREW_START);
  if (index > 0) {
    return {
      icon: trimmed.slice(0, index).trim(),
      text: trimmed.slice(index).trim(),
    };
  }
  return { icon: '', text: trimmed };
}

export function parseLettersCsv(csv: string): Record<string, ExampleWord[]> {
  const lines = csv.trim().split('\n').slice(1);
  const result: Record<string, ExampleWord[]> = {};
  lines.forEach((line) => {
    const parts = line.split(',');
    const letter = (parts[0] || '').trim();
    if (!letter) return;
    result[letter] = parts.slice(1).map(parseWordCell).filter((word) => word.text);
  });
  return result;
}

export function parseNumbersCsv(csv: string): { value: number; masculine: string; feminine: string }[] {
  return csv
    .trim()
    .split('\n')
    .slice(1)
    .map((line) => {
      const [value, masculine, feminine] = line.split(',');
      return {
        value: Number(value),
        masculine: (masculine || '').trim(),
        feminine: (feminine || '').trim(),
      };
    })
    .filter((row) => !Number.isNaN(row.value));
}
